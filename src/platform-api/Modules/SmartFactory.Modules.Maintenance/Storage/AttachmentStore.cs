using System.Text.RegularExpressions;

namespace SmartFactory.Modules.Maintenance.Storage;

/// <summary>
/// Port for attachment bytes. The domain knows only a storage key; where the bytes live is an adapter's concern:
/// local disk for Compose and tests, Azure Blob Storage from week 9.
/// </summary>
internal interface IAttachmentStore
{
    Task SaveAsync(string key, Stream content, CancellationToken cancellationToken);

    /// <summary>Returns null when the key does not exist.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

internal sealed class AttachmentStoreOptions
{
    public const string SectionName = "Attachments";

    /// <summary>Folder for the local-disk adapter. Must be outside the web root.</summary>
    public string LocalRoot { get; set; } = Path.Combine(Path.GetTempPath(), "smartfactory-attachments");
}

/// <summary>Local-disk adapter. Keys are generated by the module and validated again here (defence in depth).</summary>
internal sealed partial class LocalDiskAttachmentStore(AttachmentStoreOptions options) : IAttachmentStore
{
    private readonly string _root = Path.GetFullPath(options.LocalRoot);

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);
        var path = PathFor(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        // Why CreateNew: a key is never reused, so an existing file means a bug, not something to overwrite.
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, cancellationToken).ConfigureAwait(false);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        var path = PathFor(key);
        Stream? stream = File.Exists(path) ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true) : null;
        return Task.FromResult(stream);
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        var path = PathFor(key);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    private string PathFor(string key)
    {
        if (!KeyPattern().IsMatch(key))
        {
            throw new ArgumentException("Invalid attachment storage key.", nameof(key));
        }

        var path = Path.GetFullPath(Path.Combine(_root, key));
        return path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal)
            ? path
            : throw new ArgumentException("Attachment storage key escapes the root.", nameof(key));
    }

    /// <summary>tenant/yyyy/MM/guid.ext, the only shape the module generates.</summary>
    [GeneratedRegex(@"^[a-z0-9-]{1,64}/[0-9]{4}/[0-9]{2}/[0-9a-f]{32}\.(jpg|png|pdf)$")]
    private static partial Regex KeyPattern();
}
